# 조건수가 답하지 못하는 것을 셋으로 보인다. 전부 손으로 확인되는 행렬이다.

# (1) 절대 불확실성이 100만 배 달라도 상관행렬은 같다. 조건수도 1 로 같다.
V1 <- diag(2)
V2 <- 1e6 * diag(2)
c(SE1 = sqrt(V1[1, 1]), SE2 = sqrt(V2[1, 1]),
  조건수1 = kap(cov2cor(V1)), 조건수2 = kap(cov2cor(V2)))

# (2) 어떤 쌍의 상관도 0.5 를 넘지 않는데 조건수는 7,499.5 다.
R <- matrix(-0.4999, 3, 3); diag(R) <- 1
c(최대상관 = max(abs(R[upper.tri(R)])), 조건수 = round(kap(R), 1))

# (3) 두 블록이 각각 완벽한데(조건수 1) 전체는 1,999 다.
#     큰 전체 비가 어느 블록에도 속하지 않을 수 있다는 뜻이다.
B <- rbind(cbind(diag(2), 0.999 * diag(2)),
           cbind(0.999 * diag(2), diag(2)))
c(블록1 = kap(B[1:2, 1:2]), 블록2 = kap(B[3:4, 3:4]), 전체 = round(kap(B), 1))
