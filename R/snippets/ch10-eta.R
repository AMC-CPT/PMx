om <- function(m) {
  f <- fin(m)
  M <- matrix(f[c("OMEGA.1.1.", "OMEGA.2.1.", "OMEGA.2.1.", "OMEGA.2.2.")], 2)
  c(변이.CL = 100 * sqrt(M[1, 1]), 변이.V = 100 * sqrt(M[2, 2]),
    상관 = cov2cor(M)[1, 2])
}
round(rbind(기저 = om("100base"), 최종 = om("108wt")), 3)

