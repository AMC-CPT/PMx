# .xpt 를 거쳐 온 자료에서 0 이 0 이 아닌 일이 있다. SAS XPORT 는 IBM 16진
# 부동소수점을 쓰고 그 최소 크기가 16^-65 이다. 0 이 그 값으로 읽혀 나온다.
16^-65

# 그래서 == 0 으로 세면 하나도 못 찾는다. 크기로 봐야 한다.
x <- c(0, 16^-65, 1.2, 0)                    # .xpt 에서 읽어 온 열이라고 하자
c(`x == 0` = sum(x == 0), `abs(x) < 1e-10` = sum(abs(x) < 1e-10))

# 데이터셋 전체를 한 번에 훑는다. 0 이 아니면서 터무니없이 작은 값을 찾는다.
num <- nm[, sapply(nm, is.numeric)]
c(의심값 = sum(sapply(num, function(v) sum(v != 0 & abs(v) < 1e-10, na.rm = TRUE))))
